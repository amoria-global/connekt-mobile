export function toSwahili(text: string): string {
  if (!text) return text;
  if (SHARED_SW_EXACT[text]) return SHARED_SW_EXACT[text];
  const trimmed = text.trim();
  if (SHARED_SW_EXACT[trimmed]) return SHARED_SW_EXACT[trimmed];

  let out = text;
  for (const [re, rep] of SW_WORD_REPLACEMENTS) {
    out = out.replace(re, rep);
  }
  return out;
}

export function translateSharedSw(text: string): string {
  if (!text) return text;
  const exact = SHARED_SW_EXACT[text] ?? SHARED_SW_EXACT[text.trim()];
  if (exact) return exact;

  const trimmed = text.trim();
  const inDays = /^In (\d+) days$/i.exec(trimmed);
  if (inDays) return `Baada ya siku ${inDays[1]}`;

  const startsInH = /^Starts in (\d+)h$/i.exec(trimmed);
  if (startsInH) return `Inaanza baada ya saa ${startsInH[1]}`;

  const overdueBy = /^Overdue by (\d+)d$/i.exec(trimmed);
  if (overdueBy) return `Imechelewa kwa siku ${overdueBy[1]}`;

  const dueIn = /^Due in (\d+)d$/i.exec(trimmed);
  if (dueIn) return `Inatakiwa ndani ya siku ${dueIn[1]}`;

  const everyUnit = /^Every (day|week|month|year)$/i.exec(trimmed);
  if (everyUnit) {
    const u = everyUnit[1].toLowerCase();
    const map: Record<string, string> = { day: 'Kila siku', week: 'Kila wiki', month: 'Kila mwezi', year: 'Kila mwaka' };
    return map[u] ?? text;
  }

  const everyNUnits = /^Every (\d+) (day|week|month|year)s$/i.exec(trimmed);
  if (everyNUnits) {
    const n = everyNUnits[1];
    const u = everyNUnits[2].toLowerCase();
    const map: Record<string, string> = { day: 'siku', week: 'wiki', month: 'miezi', year: 'miaka' };
    return `Kila ${n} ${map[u] ?? u}`;
  }

  const photosCount = /^(\d+) photos?$/i.exec(trimmed);
  if (photosCount) return `Picha ${photosCount[1]}`;

  const byAuthor = /^By (.+)$/.exec(trimmed);
  if (byAuthor) return `Na ${byAuthor[1]}`;

  const paymentsWaiting = /^(\d+) payments? waiting$/i.exec(trimmed);
  if (paymentsWaiting) return `Malipo ${paymentsWaiting[1]} yanasubiri`;

  const bookingsWaitingPayment = /^(\d+) bookings? waiting for payment$/i.exec(trimmed);
  if (bookingsWaitingPayment) return `Nafasi ${bookingsWaitingPayment[1]} zinasubiri malipo`;

  const requestsWaiting = /^(\d+) booking requests? waiting$/i.exec(trimmed);
  if (requestsWaiting) return `Maombi ${requestsWaiting[1]} ya nafasi yanasubiri`;

  return toSwahili(text);
}

export function buildSwahiliDict<T extends Record<string, any>>(
  enDict: T,
  overrides: Partial<Record<keyof T, any>> = {},
): T {
  const result = {} as Record<keyof T, any>;
  for (const key of Object.keys(enDict) as (keyof T)[]) {
    const custom = overrides[key] ?? CORE_SW[key as string];
    if (custom !== undefined) {
      result[key] = custom;
    } else if (typeof enDict[key] === 'string') {
      result[key] = toSwahili(enDict[key]);
    } else {
      result[key] = enDict[key];
    }
  }
  return result as T;
}
