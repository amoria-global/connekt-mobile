const DICT: Record<Lang, Partial<Record<CopyKey, string>>> = { en, sw, rw, fr, es };

/** Fill {placeholders}. */
export function fmt(text: string, params?: Record<string, string | number>): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

export function pbCopy(lang: string | undefined, key: CopyKey, params?: Record<string, string | number>): string {
  const l = (['sw', 'rw', 'fr', 'es'].includes(lang ?? '') ? lang : 'en') as Lang;
  return fmt(DICT[l][key] ?? en[key], params);
}

/** "1 photo" / "48 photos"; undefined when the count is unknown. */
export function photoCountLabel(lang: string | undefined, n: number | undefined): string | undefined {
  if (n === undefined) return undefined;
  return n === 1 ? pbCopy(lang, 'photo_one') : pbCopy(lang, 'photo_many', { n });
}

